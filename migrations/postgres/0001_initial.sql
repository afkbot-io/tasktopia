CREATE TABLE users (
  id text PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  active_country_id text,
  created_at timestamptz NOT NULL
);

CREATE TABLE sessions (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions(user_id);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);

CREATE TABLE countries (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  seed integer NOT NULL,
  world_version bigint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL
);
CREATE INDEX countries_owner_idx ON countries(user_id);

CREATE TABLE country_members (
  country_id text NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK(role IN ('OWNER', 'MEMBER', 'VIEWER')),
  invited_by_user_id text REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL,
  PRIMARY KEY (country_id, user_id)
);
CREATE INDEX country_members_user_idx ON country_members(user_id, country_id);

ALTER TABLE users ADD CONSTRAINT users_active_country_fk
  FOREIGN KEY (active_country_id) REFERENCES countries(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE mcp_tokens (
  id text PRIMARY KEY,
  country_id text NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
  user_id text REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  token_prefix text NOT NULL,
  scopes_json jsonb NOT NULL,
  expires_at timestamptz,
  last_used_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL
);
CREATE INDEX mcp_tokens_user_active_idx ON mcp_tokens(user_id) WHERE revoked_at IS NULL;

CREATE TABLE projects (
  id text PRIMARY KEY, country_id text NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
  name text NOT NULL, description text NOT NULL DEFAULT '', status text NOT NULL DEFAULT 'ACTIVE',
  city_q integer NOT NULL, city_r integer NOT NULL, boundary_json jsonb NOT NULL, created_at timestamptz NOT NULL
);
CREATE INDEX projects_country_idx ON projects(country_id);

CREATE TABLE sprints (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name text NOT NULL, goal text NOT NULL DEFAULT '', status text NOT NULL DEFAULT 'PLANNED',
  capacity_sp integer NOT NULL DEFAULT 14, district_json jsonb NOT NULL, color text NOT NULL, created_at timestamptz NOT NULL
);
CREATE INDEX sprints_project_idx ON sprints(project_id);
CREATE UNIQUE INDEX one_active_sprint_per_project ON sprints(project_id) WHERE status = 'ACTIVE';

CREATE TABLE tasks (
  id text PRIMARY KEY, project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  sprint_id text NOT NULL REFERENCES sprints(id) ON DELETE CASCADE, title text NOT NULL,
  description text NOT NULL DEFAULT '', estimate integer NOT NULL, priority text NOT NULL DEFAULT 'NORMAL',
  status text NOT NULL DEFAULT 'PLANNING', progress integer NOT NULL DEFAULT 0, due_at timestamptz,
  building_type text NOT NULL, platform_type text NOT NULL, origin_q integer NOT NULL, origin_r integer NOT NULL,
  footprint_json jsonb NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE INDEX tasks_sprint_idx ON tasks(sprint_id);

CREATE TABLE task_comments (
  id text PRIMARY KEY, task_id text NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  body text NOT NULL, actor text NOT NULL, created_at timestamptz NOT NULL
);

CREATE TABLE roads (
