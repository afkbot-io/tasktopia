CREATE TABLE world_chunk_entities_v11 (
  country_id text NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
  chunk_x integer NOT NULL, chunk_y integer NOT NULL,
  entity_kind text NOT NULL CHECK(entity_kind IN ('DISTRICT', 'TASK', 'FEATURE')),
  entity_id text NOT NULL,
  PRIMARY KEY (country_id, chunk_x, chunk_y, entity_kind, entity_id)
);
CREATE INDEX world_chunk_entities_v11_lookup_idx
  ON world_chunk_entities_v11(country_id, entity_kind, chunk_x, chunk_y);

CREATE FUNCTION refresh_district_chunks_v14() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target_id text;
BEGIN
  target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END;
  DELETE FROM world_chunk_entities_v11 WHERE entity_kind = 'DISTRICT' AND entity_id = target_id;
  IF TG_OP <> 'DELETE' THEN
    INSERT INTO world_chunk_entities_v11(country_id, chunk_x, chunk_y, entity_kind, entity_id)
    SELECT c.country_id, floor((cell->>'x')::numeric / 64)::integer,
      floor((cell->>'y')::numeric / 64)::integer, 'DISTRICT', NEW.id
    FROM cities_v3 c CROSS JOIN LATERAL jsonb_array_elements(NEW.cells_json) cell
    WHERE c.id = NEW.city_id ON CONFLICT DO NOTHING;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER districts_v3_chunks_insert_v14 AFTER INSERT ON districts_v3
  FOR EACH ROW EXECUTE FUNCTION refresh_district_chunks_v14();
CREATE TRIGGER districts_v3_chunks_update_v14 AFTER UPDATE OF cells_json, city_id ON districts_v3
  FOR EACH ROW EXECUTE FUNCTION refresh_district_chunks_v14();
CREATE TRIGGER districts_v3_chunks_delete_v14 AFTER DELETE ON districts_v3
  FOR EACH ROW EXECUTE FUNCTION refresh_district_chunks_v14();

